#!/bin/bash

# ============================================================
# KVX Portal Backend – Codespace Environment Setup Script
# Runs automatically on `postCreateCommand` in devcontainer.
# Creates a .env file from environment variables injected
# by GitHub Codespaces Secrets.
# ============================================================

ENV_FILE=".env"

echo ""
echo "🔧 Setting up KVX Backend environment..."

# If .env already exists, skip
if [ -f "$ENV_FILE" ]; then
  echo "✅ .env already exists – skipping setup."
  exit 0
fi

echo "📝 Creating .env from Codespace environment variables..."

cat > "$ENV_FILE" <<EOF
# Server – auto-generated by scripts/setup-env.sh
NODE_ENV=${NODE_ENV:-development}
PORT=${PORT:-5000}
FRONTEND_URL=${FRONTEND_URL:-http://localhost:3000}
ALLOW_START_WITHOUT_DB=${ALLOW_START_WITHOUT_DB:-true}

# Database (Supabase)
DATABASE_URL=${DATABASE_URL}
DB_HOST=${DB_HOST}
DB_PORT=${DB_PORT:-6543}
DB_NAME=${DB_NAME:-postgres}
DB_USER=${DB_USER}
DB_PASSWORD=${DB_PASSWORD}
DB_SSL=${DB_SSL:-true}

# JWT
JWT_SECRET=${JWT_SECRET:-your_super_secret_jwt_key_change_this}
JWT_REFRESH_SECRET=${JWT_REFRESH_SECRET:-your_refresh_secret_key}

# Email
SMTP_HOST=${SMTP_HOST:-smtp.gmail.com}
SMTP_PORT=${SMTP_PORT:-587}
SMTP_USER=${SMTP_USER:-your-email@gmail.com}
SMTP_PASSWORD=${SMTP_PASSWORD:-your-app-password}

# File Upload
UPLOAD_PATH=./uploads
MAX_FILE_SIZE=10485760
EOF

echo ""

# Check critical variables
if [ -z "$DB_HOST" ] || [ -z "$DB_PASSWORD" ]; then
  echo "⚠️  WARNING: DB_HOST or DB_PASSWORD are not set."
  echo "   The server will start in degraded mode (no database)."
  echo ""
  echo "   To fix this, add the following GitHub Codespaces Secrets:"
  echo "   → Go to: https://github.com/settings/codespaces"
  echo "   → Add secrets: DB_HOST, DB_PORT, DB_NAME, DB_USER, DB_PASSWORD, DATABASE_URL"
  echo "   → Then rebuild the Codespace container."
else
  echo "✅ Database credentials found."
fi

echo ""
echo "✅ .env created successfully. Run: npm start"
echo ""
